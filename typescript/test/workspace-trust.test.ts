import assert from "node:assert/strict";
import { test } from "node:test";
import { mkdtempSync, mkdirSync, writeFileSync, realpathSync, renameSync, symlinkSync, readFileSync, rmSync } from "node:fs";
import { join } from "node:path";
import { tmpdir } from "node:os";
import { WorkspaceGrant, workspaceTrust } from "../src/config/workspace-trust.ts";

test("workspace approval narrows, applies only to its directory, and requires review on expansion", t => {
  const base = realpathSync(mkdtempSync(join(tmpdir(), "pan-trust-")));
  t.after(() => rmSync(base, {recursive:true,force:true}));
  const home = join(base, "home"); mkdirSync(home);
  const config = (workspace: string, resources: string[]) => {
    mkdirSync(join(workspace, ".pan-agent"), {recursive:true});
    writeFileSync(join(workspace, ".pan-agent/workspace.json"), JSON.stringify({version:1,resources}));
  };
  const a = join(base,"a"), b = join(base,"b"), file = "file:.env.fixture", env = "env:PAN_TEST_CREDENTIAL";
  config(a,[file,env]); config(b,[file,env]);
  const request = workspaceTrust(a,home);
  assert.deepEqual(request.eligible,[]);
  assert.throws(() => workspaceTrust(b,home,request.revision), /review_changed/);
  assert.deepEqual(workspaceTrust(a,home,request.revision).eligible,[env,file]);
  config(a,[file]);
  assert.deepEqual(workspaceTrust(a,home).eligible,[file]);
  config(a,[file,env]);
  assert.deepEqual(workspaceTrust(a,home).eligible,[file]);
  assert.deepEqual(workspaceTrust(b,home).eligible,[]);
  const parentSettings = join(home,".pan-agent","settings.json");
  symlinkSync(join(a,".pan-agent/workspace.json"),parentSettings);
  assert.throws(()=>workspaceTrust(a,home), /unsafe_parent_settings/);
  rmSync(parentSettings);
  const path = join(a,".env.fixture");
  writeFileSync(path,"synthetic");
  const make = () => new WorkspaceGrant(a,home,{resource:file,command:"test grant"},[],()=>{});
  const g = make();
  assert.throws(()=>g.start(b), /workspace_changed/);
  g.start(a);
  assert.equal(g.take("different"),undefined);
  assert.equal(g.take("test grant"),"synthetic");
  assert.equal(g.take("test grant"),undefined);
  g.start(a); assert.equal(g.take("test grant"),undefined);
  const stale = make(); stale.start(a);
  renameSync(path,path+".prior"); writeFileSync(path,"synthetic");
  assert.throws(()=>stale.take("test grant"), /approval_expired/);
  const changed = make(); changed.start(a); writeFileSync(path,"replacement");
  assert.throws(()=>changed.take("test grant"), /approval_expired/);
  rmSync(path); symlinkSync(path+".prior",path);
  assert.throws(make);
  const record = join(a,".pan-agent/workspace.json");
  writeFileSync(record, '{"version":1,"resources":[],"resources":["env:PAN_TEST_CREDENTIAL"]}');
  assert.throws(()=>workspaceTrust(a,home), /duplicate_property/);
  config(a,[file,env]);
  renameSync(record,record+".original");symlinkSync(record+".original",record);
  assert.throws(()=>workspaceTrust(a,home));
  assert.match(readFileSync(record+".original","utf8"),/fixture/);
});
